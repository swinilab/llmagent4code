"""
Load-test plan and instrumentation for OMS performance verification.

Tool: locust (Python-based, distributed-capable load testing)
Scenarios:
  1. Baseline: 500 concurrent users, 5-minute ramp, 10-minute steady
  2. Sustained: 5,000 concurrent sessions, 10-minute steady
  3. Spike: 3x baseline spike (1,500 → 4,500) ramping over 60s

Metrics collected:
  - p50/p95/p99 latency (ms)
  - Throughput (req/s)
  - Error rate (%)
  - CPU utilization (%)
  - Queue depth (rate limiter tokens)
  - Circuit-breaker transitions

Pass/fail thresholds (NFR 1.1-1.3):
  - Checkout journey p95 ≤ 300ms, p99 ≤ 600ms
  - Product search p95 ≤ 150ms
  - Average queueing time < 50ms
  - CPU utilization 60-85% at peak
  - Zero crashes, unbounded memory growth, or silent request loss
"""
from locust import HttpUser, task, between, events
import time
import json
import asyncio
import httpx

# Checkout journey: create order → pay → check status
CHECKOUT_STEPS = ["create_order", "pay_order", "get_order"]

# Dynamically discovered entity IDs — populated by on_test_start
CUSTOMER_ID = None
PRODUCT_IDS = []


@events.test_start.add_listener
async def on_test_start(environment, **kwargs):
    """Create test entities on locust start and capture their auto-generated IDs.

    This replaces the previous hardcoded IDs (test-customer-001, test-product-001)
    which could never match the UUIDs generated by the ORM models.
    """
    global CUSTOMER_ID, PRODUCT_IDS
    base_url = environment.host
    async with httpx.AsyncClient(base_url=base_url, timeout=30) as client:
        # Create a test customer
        resp = await client.post("/api/v1/customers", json={
            "name": "Load Test Customer",
            "address": "123 Test St, Springfield",
            "phone": "+1-555-9999",
            "banking_details": "LOAD-TEST-ACC-001",
            "role": "CUSTOMER",
        })
        if resp.status_code == 201:
            CUSTOMER_ID = resp.json()["id"]
            print(f"Created test customer: {CUSTOMER_ID}")
        else:
            # Fallback: list existing customers and use the first one
            resp = await client.get("/api/v1/customers")
            customers = resp.json()
            if customers:
                CUSTOMER_ID = customers[0]["id"]
                print(f"Using existing customer: {CUSTOMER_ID}")
            else:
                raise RuntimeError("Failed to create or find a test customer")

        # Create test products
        for name, price in [("Load Test Product A", 29.99), ("Load Test Product B", 49.99)]:
            resp = await client.post("/api/v1/products", json={
                "name": name,
                "description": f"Load test product: {name}",
                "base_price": price,
                "stock_available": 10000,
            })
            if resp.status_code == 201:
                pid = resp.json()["id"]
                PRODUCT_IDS.append(pid)
                print(f"Created product '{name}': {pid}")
            else:
                # Fallback: list existing products
                resp = await client.get("/api/v1/products")
                products = resp.json()
                for p in products:
                    if p["name"] == name:
                        PRODUCT_IDS.append(p["id"])
                        print(f"Using existing product '{name}': {p['id']}")
                        break

        if not CUSTOMER_ID:
            raise RuntimeError("Failed to set up test customer for load test")
        if len(PRODUCT_IDS) < 1:
            raise RuntimeError("Failed to set up test products for load test")

        print(f"Load test setup complete: customer={CUSTOMER_ID}, products={PRODUCT_IDS}")


class OMSUser(HttpUser):
    """Simulated OMS user performing e-commerce workflows."""
    wait_time = between(0.5, 2.0)  # think time between requests

    def on_start(self):
        """Initialize session state."""
        self.order_id = None
        self.order_version = 1

    @task(3)
    def browse_products(self):
        """Product search/browse (latency-sensitive, p95 ≤ 150ms)."""
        self.client.get("/api/v1/products", name="list_products")
        self.client.get("/api/v1/products?q=test", name="search_products")

    @task(2)
    def checkout_journey(self):
        """Full checkout journey: create order → pay → verify."""
        if not CUSTOMER_ID or not PRODUCT_IDS:
            return

        # Step 1: Create order
        with self.client.post(
            "/api/v1/orders",
            json={
                "customer_id": CUSTOMER_ID,
                "line_items": [
                    {"product_id": PRODUCT_IDS[0], "quantity": 1},
                ],
            },
            name="create_order",
            catch_response=True,
        ) as resp:
            if resp.status_code == 201:
                data = resp.json()
                self.order_id = data["id"]
                self.order_version = data["version"]
            elif resp.status_code == 429:
                resp.failure("Rate limited")
            else:
                resp.failure(f"Unexpected status: {resp.status_code}")

        if not self.order_id:
            return

        # Step 2: Pay order (checkout-critical)
        with self.client.post(
            f"/api/v1/orders/{self.order_id}/pay",
            json={
                "amount": "99.99",
                "method": "CREDIT_CARD",
                "idempotency_key": f"pay-{self.order_id}-{time.time()}",
            },
            name="pay_order",
            catch_response=True,
        ) as resp:
            if resp.status_code == 200:
                pass
            elif resp.status_code == 429:
                resp.failure("Rate limited")
            else:
                resp.failure(f"Payment failed: {resp.status_code}")

        # Step 3: Get order status
        self.client.get(
            f"/api/v1/orders/{self.order_id}",
            name="get_order",
        )

    @task(1)
    def get_recommendations(self):
        """Non-essential feature (circuit-breaker protected)."""
        if not CUSTOMER_ID:
            return
        self.client.get(
            f"/api/v1/recommendations/{CUSTOMER_ID}",
            name="get_recommendations",
        )

    @task(1)
    def health_check(self):
        """Health endpoint (low overhead)."""
        self.client.get("/health", name="health_check")


@events.init.add_listener
def on_locust_init(environment, **kwargs):
    """Log test start."""
    print("=" * 60)
    print("OMS Load Test Starting")
    print(f"Target: {environment.host}")
    print("Scenarios: browse, checkout, recommendations, health")
    print("=" * 60)
